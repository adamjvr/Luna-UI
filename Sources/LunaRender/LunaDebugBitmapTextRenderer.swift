// Small public CPU proof renderer for readable ASCII diagnostics and early
// application bring-up. Production shaped text continues to belong to LunaText,
// but downstream Luna applications should not need to duplicate the test app's
// private bitmap-font implementation merely to display real document content.

public enum LunaDebugBitmapTextRenderer {
    public static let glyphWidth = 5
    public static let glyphHeight = 7
    public static let advance = 6

    /// Draw clipped ASCII text directly into a Luna BGRA framebuffer.
    public static func draw(
        _ text: String,
        atX x: Int,
        y: Int,
        scale: Int = 1,
        color: LunaRGBA8,
        maximumWidth: Int? = nil,
        into framebuffer: inout LunaFramebuffer
    ) {
        let s = max(1, scale)
        let fbWidth = framebuffer.width
        let fbHeight = framebuffer.height
        guard fbWidth > 0, fbHeight > 0, !text.isEmpty else { return }

        let widthLimit = maximumWidth.map { max(0, $0) }

        framebuffer.withUnsafeMutablePixelBytes { base, strideBytes in
            let safeByteCount = strideBytes * fbHeight
            guard safeByteCount > 0 else { return }

            @inline(__always)
            func writePixel(_ px: Int, _ py: Int) {
                guard px >= 0, py >= 0, px < fbWidth, py < fbHeight else { return }
                let offset = py * strideBytes + px * 4
                guard offset >= 0, offset + 3 < safeByteCount else { return }
                let pixel = base.advanced(by: offset)
                pixel[0] = color.b
                pixel[1] = color.g
                pixel[2] = color.r
                pixel[3] = color.a
            }

            @inline(__always)
            func fillSpan(rowY: Int, x0: Int, x1: Int) {
                guard rowY >= 0, rowY < fbHeight else { return }
                let clippedStart = max(0, x0)
                let clippedEnd = min(fbWidth, x1)
                guard clippedEnd > clippedStart else { return }

                var pixel = base.advanced(by: rowY * strideBytes + clippedStart * 4)
                for _ in clippedStart..<clippedEnd {
                    pixel[0] = color.b
                    pixel[1] = color.g
                    pixel[2] = color.r
                    pixel[3] = color.a
                    pixel = pixel.advanced(by: 4)
                }
            }

            var penX = x
            for scalar in text.unicodeScalars {
                let code = Int(scalar.value)
                if code == 10 {
                    break
                }

                if let widthLimit, penX - x + advance * s > widthLimit {
                    break
                }

                defer { penX += advance * s }
                guard code >= 32, code <= 127 else { continue }
                guard penX < fbWidth, penX + glyphWidth * s > 0 else { continue }
                guard y < fbHeight, y + glyphHeight * s > 0 else { continue }

                let glyphBase = (code - 32) * glyphWidth
                for column in 0..<glyphWidth {
                    let bits = font5x7[glyphBase + column]
                    guard bits != 0 else { continue }
                    let px = penX + column * s
                    guard px < fbWidth, px + s > 0 else { continue }

                    for row in 0..<glyphHeight where ((bits >> row) & 1) != 0 {
                        let py = y + row * s
                        if s == 1 {
                            writePixel(px, py)
                        } else {
                            for scaledY in py..<(py + s) {
                                fillSpan(rowY: scaledY, x0: px, x1: px + s)
                            }
                        }
                    }
                }
            }
        }
    }

